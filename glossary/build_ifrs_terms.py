def build(path: Path) -> int:
    seen = set()
    rows = []
    for en, ar, ksa, cat, status in TERMS:
        key = en.lower()
        if key in seen:
            raise ValueError(f"duplicate term: {en}")
        seen.add(key)
        rows.append({"en": en, "ar": ar, "ar_ksa": ksa, "category": cat, "status": status})
    # utf-8-sig so Excel shows the Arabic correctly
    with open(path, "w", encoding="utf-8-sig", newline="") as f:
        w = csv.DictWriter(f, fieldnames=["en", "ar", "ar_ksa", "category", "status"])
        w.writeheader()
        w.writerows(rows)
    return len(rows)


